"""Copy the tuned hyperparameters of one experiment into a sibling experiment (ablation variants share the winner).

    python tools/apply_winner.py configs/exp/SM_rumboost_tuned.yaml configs/exp/SM_rumboost_nomono.yaml
        -> configs/exp/SM_rumboost_nomono_tuned.yaml   (dst overrides deep-merged OVER the winner's overrides)

Use: RUMBoost ablations (no monotone / no z / functional effect / PCUF) keep the official variant's boosting
hyperparameters so the ablation changes one thing.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from run import _deep_merge  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("winner", help="<stem>_tuned.yaml written by tune.py")
    ap.add_argument("dst", help="base yaml of the variant that should inherit the winner's hyperparameters")
    ap.add_argument("--out", default=None, help="default: <dst stem>_tuned.yaml")
    ap.add_argument("--keys", nargs="*", default=["boost_config", "train_config", "benchmark_config", "model_config"],
                    help="override sections copied from the winner")
    a = ap.parse_args()
    win = yaml.safe_load(Path(a.winner).read_text(encoding="utf-8")) or {}
    dst = yaml.safe_load(Path(a.dst).read_text(encoding="utf-8")) or {}
    inherited = {k: v for k, v in (win.get("overrides") or {}).items() if k in a.keys}
    doc = dict(dst)
    doc["overrides"] = _deep_merge(inherited, dst.get("overrides") or {})
    out = Path(a.out) if a.out else Path(a.dst).with_name(Path(a.dst).stem + "_tuned.yaml")
    header = (f"# AUTO-GENERATED by tools/apply_winner.py: {Path(a.dst).name} + hyperparameters of {Path(a.winner).name}\n"
              f"# Run: python run.py {out.relative_to(ROOT).as_posix() if out.is_relative_to(ROOT) else out}\n")
    out.write_text(header + yaml.safe_dump(doc, default_flow_style=False, sort_keys=False, allow_unicode=True),
                   encoding="utf-8", newline="\n")
    print(f"[apply_winner] wrote {out}")


if __name__ == "__main__":
    main()
